# Generates Sources/EasyKey/engine/MixedWordsData.h, the word list of the mixed English and Vietnamese mode.
# For the keys of a word as typed it keeps how common the word is in English and how common the Vietnamese
# word is that Telex makes of the same keys, so the engine can tell "this" (English) from "thí" (Vietnamese).
# Word frequencies come from wordfreq (https://github.com/rspeer/wordfreq by Robyn Speer, data under CC BY-SA 4.0).
# Usage: python tools/make_mixed_words.py [--check] <EngineTests>  (needs: pip install wordfreq)
#   build the engine tests first (docs/BUILD.md); EngineTests --render shows what Telex makes of each word.
import os, re, subprocess, sys
import wordfreq

check_mode = '--check' in sys.argv
args = [a for a in sys.argv[1:] if a != '--check']

if not args:
    print("Usage: python tools/make_mixed_words.py [--check] <path-to-EngineTests>")
    sys.exit(1)

ENGINE_TESTS = args[0]
OUT = 'Sources/EasyKey/engine/MixedWordsData.h'
# must match MIXED_VIETNAMESE_LEAN and MIXED_CONTEXT_WEIGHT in Engine.cpp (Zipf x10)
LEAN, CONTEXT = 5, 20
ENGLISH_WORDS = 60000  # English words to look at, most common first
CHANGED_MIN = 30       # an English word Telex changes ("this" -> "thí") is kept from this Zipf x10 up
CONTEXT_MIN = 50       # a word Telex leaves alone ("the") is kept from here, only to tell the language of the text
VIETNAMESE_MIN = 45    # same for a Vietnamese word typed without marks ("anh", "con")

# Curated tech and daily words guaranteed to be kept even if frequency is borderline
CURATED_WHITELIST = {
    'excited', 'memory', 'system', 'explain', 'explore', 'example',
    'process', 'service', 'message', 'language', 'keyboard', 'software',
    'hardware', 'update', 'install', 'config', 'debug', 'error',
    'warning', 'branch', 'commit', 'merge', 'pull', 'push', 'build',
    'release', 'runtime', 'thread', 'cache', 'token', 'session',
    'request', 'response', 'endpoint', 'plugin', 'module', 'package',
    'repository', 'ok', 'cool', 'nice', 'lol', 'omg', 'btw', 'idk',
    'tbh', 'imho', 'pls', 'thx', 'stream', 'content', 'creator',
    'fan', 'like', 'share', 'comment', 'follow', 'unsubscribe',
    'fix', 'fixed', 'fixes', 'fixing'
}

# a Vietnamese syllable without marks; an English word that isn't one ("you", "are") is no Vietnamese word,
# whatever the Vietnamese counts say (they come from text that mixes in English)
SYLLABLE = re.compile('^(ngh|ng|gh|gi|kh|nh|ph|qu|th|tr|ch|[bcdghklmnprstvx])?'
                      '(oai|oay|uay|uya|uyu|ieu|yeu|uoi|uou|ai|ao|au|ay|eo|eu|ia|iu|oa|oe|oi|oo|ua|ue|ui|uy|ie|uo|ye|a|e|i|o|u|y)'
                      '(ch|ng|nh|[cmnpt])?$')

def zipf(word, lang):
    return min(78, round(wordfreq.zipf_frequency(word, lang) * 10))

english = [w for w in wordfreq.top_n_list('en', ENGLISH_WORDS) if w.isascii() and w.isalpha() and w.islower()]
out = subprocess.run([ENGINE_TESTS, '--render'], input='\n'.join(english) + '\n',
                     capture_output=True, text=True, encoding='utf-8', check=True).stdout
telex = dict(line.split('\t') for line in out.splitlines())

words = {}
for w in english:
    en, typed = zipf(w, 'en'), telex[w]
    if typed != w:
        vi = zipf(typed, 'vi')  # 0 when Telex made no Vietnamese word of it ("different" -> "diferent")
        if (en >= CHANGED_MIN and en + CONTEXT > vi + LEAN) or (w in CURATED_WHITELIST and en + CONTEXT > vi + LEAN):
            words[w] = (en, vi)
    elif en >= CONTEXT_MIN or w in CURATED_WHITELIST:
        words[w] = (en, zipf(w, 'vi') if SYLLABLE.match(w) else 0)
for w in wordfreq.top_n_list('vi', 8000):
    if SYLLABLE.match(w) and w not in words and telex.get(w, w) == w and zipf(w, 'vi') >= VIETNAMESE_MIN:
        words[w] = (zipf(w, 'en'), zipf(w, 'vi'))

lines = [w + chr(48 + en) + chr(48 + vi) for w, (en, vi) in sorted(words.items())]

content = '//\n//  MixedWordsData.h\n//  EasyKey\n//\n'
content += '//  Generated by tools/make_mixed_words.py, do not edit. Word frequencies from wordfreq\n'
content += '//  (https://github.com/rspeer/wordfreq), data under CC BY-SA 4.0.\n'
content += '//  SPDX-License-Identifier: GPL-3.0-only AND CC-BY-SA-4.0\n//\n\n'
content += '#define MIXED_WORD_COUNT %d\n\n' % len(lines)
content += 'static const char MIXED_WORDS[] =\n'

chunk = ''
for line in lines:
    chunk += line.replace('\\', '\\\\').replace('"', '\\"').replace('?', '\\?') + '\\n'
    if len(chunk) > 100:
        content += '    "%s"\n' % chunk
        chunk = ''
content += '    "%s";\n' % chunk

if check_mode:
    if os.path.exists(OUT):
        with open(OUT, 'r', encoding='utf-8') as f:
            existing = f.read()
        if existing == content:
            print(f"Check passed: {OUT} matches generated words ({len(lines)} words).")
            sys.exit(0)
        else:
            print(f"Check failed: {OUT} differs from generated content.")
            sys.exit(1)
    else:
        print(f"Check failed: {OUT} does not exist.")
        sys.exit(1)

old_count = 0
old_bytes = 0
if os.path.exists(OUT):
    old_bytes = os.path.getsize(OUT)
    with open(OUT, 'r', encoding='utf-8') as f:
        for l in f:
            if l.startswith('#define MIXED_WORD_COUNT'):
                old_count = int(l.split()[2])
                break

with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write(content)

new_bytes = os.path.getsize(OUT)
delta_words = len(lines) - old_count
delta_bytes = new_bytes - old_bytes
print(f"{len(lines)} words ({new_bytes} bytes). Delta: {delta_words:+d} words, {delta_bytes:+d} bytes.")
