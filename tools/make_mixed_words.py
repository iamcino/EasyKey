# Generates Sources/EasyKey/engine/MixedWordsData.h, the word list of the mixed English and Vietnamese mode.
# For the keys of a word as typed it keeps how common the word is in English and how common the Vietnamese
# word is that Telex makes of the same keys, so the engine can tell "this" (English) from "thí" (Vietnamese).
# Word frequencies come from wordfreq (https://github.com/rspeer/wordfreq by Robyn Speer, data under CC BY-SA 4.0).
# Usage: python tools/make_mixed_words.py <EngineTests>  (needs: pip install wordfreq)
#   build the engine tests first (docs/BUILD.md); EngineTests --render shows what Telex makes of each word.
import re, subprocess, sys
import wordfreq

ENGINE_TESTS = sys.argv[1]
OUT = 'Sources/EasyKey/engine/MixedWordsData.h'
# must match MIXED_VIETNAMESE_LEAN and MIXED_CONTEXT_WEIGHT in Engine.cpp (Zipf x10)
LEAN, CONTEXT = 5, 20
ENGLISH_WORDS = 60000  # English words to look at, most common first
CHANGED_MIN = 30       # an English word Telex changes ("this" -> "thí") is kept from this Zipf x10 up
CONTEXT_MIN = 50       # a word Telex leaves alone ("the") is kept from here, only to tell the language of the text
VIETNAMESE_MIN = 45    # same for a Vietnamese word typed without marks ("anh", "con")

# a Vietnamese syllable without marks; an English word that isn't one ("you", "are") is no Vietnamese word,
# whatever the Vietnamese counts say (they come from text that mixes in English)
SYLLABLE = re.compile('^(ngh|ng|gh|gi|kh|nh|ph|qu|th|tr|ch|[bcdghklmnprstvx])?'
                      '(oai|oay|uay|uya|uyu|ieu|yeu|uoi|uou|ai|ao|au|ay|eo|eu|ia|iu|oa|oe|oi|oo|ua|ue|ui|uy|ie|uo|ye|a|e|i|o|u|y)'
                      '(ch|ng|nh|[cmnpt])?$')

def zipf(word, lang):
    return min(78, round(wordfreq.zipf_frequency(word, lang) * 10))

english = [w for w in wordfreq.top_n_list('en', ENGLISH_WORDS) if w.isascii() and w.isalpha() and w.islower()]
out = subprocess.run([ENGINE_TESTS, '--render'], input='\n'.join(english) + '\n',
                     capture_output=True, text=True, encoding='utf-8', check=True).stdout
telex = dict(line.split('\t') for line in out.splitlines())

words = {}
for w in english:
    en, typed = zipf(w, 'en'), telex[w]
    if typed != w:
        vi = zipf(typed, 'vi')  # 0 when Telex made no Vietnamese word of it ("different" -> "diferent")
        if en >= CHANGED_MIN and en + CONTEXT > vi + LEAN:  # leave out a word that would never win
            words[w] = (en, vi)
    elif en >= CONTEXT_MIN:
        words[w] = (en, zipf(w, 'vi') if SYLLABLE.match(w) else 0)
for w in wordfreq.top_n_list('vi', 8000):
    if SYLLABLE.match(w) and w not in words and telex.get(w, w) == w and zipf(w, 'vi') >= VIETNAMESE_MIN:
        words[w] = (zipf(w, 'en'), zipf(w, 'vi'))

lines = [w + chr(48 + en) + chr(48 + vi) for w, (en, vi) in sorted(words.items())]
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('//\n//  MixedWordsData.h\n//  EasyKey\n//\n')
    f.write('//  Generated by tools/make_mixed_words.py, do not edit. Word frequencies from wordfreq\n')
    f.write('//  (https://github.com/rspeer/wordfreq), data under CC BY-SA 4.0.\n')
    f.write('//  SPDX-License-Identifier: GPL-3.0-only AND CC-BY-SA-4.0\n//\n\n')
    f.write('#define MIXED_WORD_COUNT %d\n\n' % len(lines))
    f.write('static const char MIXED_WORDS[] =\n')
    # short literals: MSVC takes at most 16 KB in one
    chunk = ''
    for line in lines:
        chunk += line.replace('\\', '\\\\').replace('"', '\\"').replace('?', '\\?') + '\\n'
        if len(chunk) > 100:
            f.write('    "%s"\n' % chunk)
            chunk = ''
    f.write('    "%s";\n' % chunk)
print(len(lines), 'words,', sum(len(l) + 1 for l in lines), 'bytes')
